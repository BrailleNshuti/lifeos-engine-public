"""The architecture, drawn from the code itself.

Reads every module's real `from . import x` lines, computes each module's depth (0 = imports no other engine module,
otherwise 1 + the deepest module it imports) and draws the graph as Mermaid. `docs/ARCHITECTURE-GRAPH.md` is generated by
`lifeos arch --write`; a test fails when the checked-in file no longer matches the code, so the picture cannot go stale.
"""
import ast
from pathlib import Path

PKG = Path(__file__).resolve().parent


def _imports(tree, names):
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.level == 1:
            if node.module:
                found.add(node.module.split(".")[0])
            else:
                found.update(a.name for a in node.names)
    return sorted(n for n in found if n in names)


def graph():
    trees = {p.stem: ast.parse(p.read_text(encoding="utf-8")) for p in sorted(PKG.glob("*.py")) if p.stem != "__init__"}
    names = set(trees)
    imports = {n: [i for i in _imports(t, names) if i != n] for n, t in trees.items()}
    depth = {}

    def of(n, stack=()):
        if n in depth:
            return depth[n]
        if n in stack:
            raise ValueError(f"import cycle through {n}")
        depth[n] = 1 + max(of(i, stack + (n,)) for i in imports[n]) if imports[n] else 0
        return depth[n]

    return {n: {"depth": of(n), "imports": imports[n]} for n in sorted(names)}


def mermaid(g):
    lines = ["graph BT"]
    for d in sorted({v["depth"] for v in g.values()}):
        members = [n for n, v in g.items() if v["depth"] == d]
        lines.append(f"  subgraph L{d}[depth {d}]")
        lines += [f"    {n}[{n}]" for n in members]
        lines.append("  end")
    lines += [f"  {n} --> {i}" for n, v in g.items() for i in v["imports"]]
    return "\n".join(lines)


def page():
    g = graph()
    deepest = max(v["depth"] for v in g.values())
    return (f"# Architecture graph\n\nGenerated by `lifeos arch --write docs/ARCHITECTURE-GRAPH.md` from the real imports. "
            f"Do not edit by hand: a test fails when this file no longer matches the code.\n\n"
            f"{len(g)} modules, {sum(len(v['imports']) for v in g.values())} import edges, {deepest + 1} depths "
            f"(depth 0 imports no other engine module; an arrow points from the importer to what it uses).\n\n"
            f"```mermaid\n{mermaid(g)}\n```\n")
