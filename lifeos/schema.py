"""`lifeos schema`: the format of every file the engine writes, generated from the code that writes them.

Columns come from the modules' own header constants, so this page cannot disagree with the code (a test pins it).
Everything here is plain text you can read, diff and back up; logs only ever grow.
"""
from . import calibrate, experiment, learn, log, vocab

CSV_LOGS = [  # file, written by, columns, note
    ("logs/proofs.csv", "`lifeos log proof`", log.HEADERS["proofs.csv"], "One row per proof (rule 1): a link, test or score."),
    ("logs/ledger.csv", "`lifeos log ledger`, `ask`, `mcp`", log.HEADERS["ledger.csv"], "Minutes saved per task; feeds `week` and `experiment`."),
    ("logs/health.csv", "`lifeos log health`", log.HEADERS["health.csv"], "Your own sleep, gym and energy numbers (class B)."),
    ("logs/hours.csv", "`lifeos log hours`", log.HEADERS["hours.csv"], "Hours per area: german, study, lab, work."),
    ("logs/ratings.csv", "`lifeos rate`", learn.HEADER, "Your 1-5 score per model and kind of task; `learn` reads it."),
    ("logs/predictions.csv", "`predict`, `resolve`, `decide`", calibrate.HEADER, "Two row kinds: predict (value = percent) and resolve (value = 1 or 0)."),
    ("logs/vocab.csv", "`vocab`", vocab.HEADER, "Two row kinds: add and review; boxes with gaps of 0, 1, 3, 7, 14 days."),
    ("logs/experiments.csv", "`experiment`", experiment.HEADER, "Two row kinds: start (value = baseline) and end (value = result)."),
]


def page():
    lines = ["# Log formats", "",
             "Generated by `lifeos schema --write docs/LOGS.md`. Do not edit by hand: a test fails if it drifts from the code.",
             "", "All CSV logs are UTF-8 with a header row. They only grow: nothing rewrites or deletes a row. "
             "Readers skip a damaged row instead of failing.", ""]
    for name, who, cols, note in CSV_LOGS:
        lines += [f"## {name}", "", f"Written by {who}. {note}", "", "| " + " | ".join(cols) + " |",
                  "|" + "---|" * len(cols), ""]
    lines += ["## logs/runs.jsonl", "",
              "One JSON object per line, written by `ask`, `delegate`, `panel`, `canary` and others. Each new record carries "
              "`prev_hash`, the SHA-256 of the line before it, so `lifeos verify` can prove nothing was edited, removed or "
              "reordered. No prompt text is stored, only sizes, hashes and flags.", "",
              "## tasks/T-YYMMDD-slug.md", "",
              "Front matter: `id`, `goal`, `done_when`, `route`, `level` (L0-L3), `status` (inbox, todo, doing, blocked, done), "
              "`due`. Checked by `lifeos lint`.", "",
              "## decisions/D-YYMMDD-slug.md", "",
              "Front matter: `id`, `title`, `date`, `revisit`, `prediction`. Written by `lifeos decide`.", "",
              "## pipelines/NAME.json", "",
              "`{\"steps\": [{\"name\": ..., \"argv\": [...], \"gate\": \"stop\" | \"continue\"}]}`. Run by `lifeos pipeline`.", ""]
    return "\n".join(lines)
